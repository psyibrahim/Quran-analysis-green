/**
 * تنظيف مدخل الجذر من المسافات والشُرَط (مثل "ع ذ ب" أو "ع-ذ-ب" -> "عذب")
 */
export function normalizeRootInput(input: string): string {
  if (!input) return '';
  const cleaned = input
    .replace(/[\s\-_ـ.]+/g, '')
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();
  
  // إذا كانت الكلمة مسجلة في القاموس الصريح
  if (QURANIC_COMMON_ROOTS[cleaned]) {
    return QURANIC_COMMON_ROOTS[cleaned];
  }
  
  // إذا كانت 3 أحرف مباشرة فهي تمثل الجذر ذاته
  if (cleaned.length === 3) {
    return cleaned;
  }

  return cleaned;
}

/**
 * تجريد الكلمة العربية إلى أقرب جذر ثلاثي قياسي
 */
export function extractCandidateArabicRoot(word: string): string {
  let w = normalizeQuranicToken(word);
  if (!w || w.length <= 2) return w;

  // إذا كانت مسجلة في القاموس
  if (QURANIC_COMMON_ROOTS[w]) {
    return QURANIC_COMMON_ROOTS[w];
  }

  // إزالة سوابق الاستفهام والعطف والجر والتعريف
  w = w.replace(/^(افب|اوب|افال|اوال|وبال|فبال|وكال|فكال|بال|كال|فال|وال|لل|ولل|فلل|ال|ول|فل|وب|فb|وك|فك|يا|ويا|فيا)/, '');
  w = w.replace(/^(و|ف|ب|ل|ك|س)/, '');

  // إذا بقيت 3 أحرف
  if (w.length === 3) return w;

  // إزالة اللواحق الشائعة (الضمائر، علامات التأنيث والجمع، التنوين)
  w = w.replace(/(هما|هم|هن|ها|كم|كن|كما|نا|ين|ون|ات|ان|يه|ته|تك|تم|تن|ني|ي|ه|ك|ت|ا)$/, '');

  if (w.length === 3) return w;

  // إزالة سوابق المضارعة والاشتقاق (است، مت، مست، ان، يت، تت، نت، أ، ي، ت، ن، م)
  w = w.replace(/^(است|مست|مت|من|ان|يت|تت|نت)/, '');
  if (w.length > 3) {
    w = w.replace(/^(ي|ت|ن|ا|م)/, '');
  }

  // إزالة حشو التاء والألف والواو والياء الزائدة في أوزان (افتعل، فاعل، مفعول، تفعيل)
  if (w.length === 4) {
    // وزن فاعل (حذف الألف الثانية): مثل عابد -> عبد، رازق -> رزق، عالم -> علم
    if (w[1] === 'ا') {
      return w[0] + w.slice(2);
    }
    // وزن فعيل / فعول (حذف الياء أو الواو الثالثة): مثل رحيم -> رحم، غفور -> غفر
    if (w[2] === 'ي' || w[2] === 'و' || w[2] === 'ا') {
      return w.slice(0, 2) + w.slice(3);
    }
    // وزن تفعّل / افتعل (حذف التاء الثانية): مثل اعتمر -> عمر
    if (w[1] === 'ت') {
      return w[0] + w.slice(2);
    }
  }

  if (w.length === 5) {
    // وزن مفعول (حذف الميم والواو): مثل معلوم -> علم، مكتوب -> كتب
    if (w.startsWith('م') && w[3] === 'و') {
      return w.slice(1, 3) + w.slice(4);
    }
    // وزن استفعال / افتعال
    if (w[1] === 'ت' && w[3] === 'ا') {
      return w[0] + w[2] + w[4];
    }
  }

  return w.length >= 3 ? w.slice(0, 3) : w;
}

/**
 * فحص ما إذا كان التوكن ينتمي إلى جذر الكلمة المطلوبة
 */
export function isTokenInRoot(tokenClean: string, rootOrQuery: string): boolean {
  if (!tokenClean || !rootOrQuery) return false;
  const targetRoot = normalizeRootInput(rootOrQuery);
  const tokenCandidate = extractCandidateArabicRoot(tokenClean);

  if (tokenCandidate === targetRoot) return true;

  // فحص الاحتواء الحتمي لحروف الجذر الثلاثية بالتسلسل الصرفي داخل الكلمة
  if (targetRoot.length === 3) {
    const c1 = targetRoot[0];
    const c2 = targetRoot[1];
    const c3 = targetRoot[2];
    
    // تأكد أن الحروف تظهر بنفس الترتيب
    const idx1 = tokenClean.indexOf(c1);
    if (idx1 !== -1) {
      const idx2 = tokenClean.indexOf(c2, idx1 + 1);
      if (idx2 !== -1 && idx2 - idx1 <= 2) {
        const idx3 = tokenClean.indexOf(c3, idx2 + 1);
        if (idx3 !== -1 && idx3 - idx2 <= 2) {
          // منع التطابقات الطفيلية للكلمات البعيدة جداً
          if (tokenClean.length <= 9) {
            return true;
          }
        }
      }
    }
  }

  return false;
}
